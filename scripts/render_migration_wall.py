"""Render the homepage migration wall from scripts/migration_test/migration_results.csv.

Usage: python3 scripts/render_migration_wall.py [--check]
--check exits 1 when docs/website/index.html is out of date instead of rewriting it.
"""

import csv
import html
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "scripts/migration_test/migration_results.csv"
PAGE = ROOT / "docs/website/index.html"
START = "<!-- migration-wall:start (generated by scripts/render_migration_wall.py) -->"
END = "<!-- migration-wall:end -->"
INDENT = "        "


def headline(count: int) -> str:
    """Public figure: rounded down to a multiple of 5 with a plus, e.g. 69 -> "65+"."""
    return f"{count - count % 5}+"


def render(rows: list[dict[str, str]]) -> str:
    migrated = [r for r in rows if r["TestStatusAfterMigration"] in ("PASS", "FAIL")]
    passed = [r for r in migrated if r["TestStatusAfterMigration"] == "PASS"]
    groups: dict[str, list[dict[str, str]]] = defaultdict(list)
    for row in passed:
        language = "TypeScript" if row["Language"] == "TS/JS" else row["Language"]
        groups[f"{row['Package']} · {language}"].append(row)

    lines = [
        START,
        '<details class="migration-wall reveal">',
        f"  <summary>See the repositories "
        f"<span>{headline(len(passed))} migrated repositories still pass</span></summary>",
        '  <div class="wall-groups">',
    ]
    for name, items in sorted(groups.items(), key=lambda item: (-len(item[1]), item[0])):
        lines.append(f'    <div class="wall-group"><h3>{html.escape(name)} <span>{len(items)}</span></h3><ul>')
        for row in sorted(items, key=lambda r: r["RepoURL"].lower()):
            url = row["RepoURL"].rstrip("/")
            if not re.fullmatch(r"https://github\.com/[\w.-]+/[\w.-]+", url):
                raise SystemExit(f"unexpected repository URL: {url!r}")
            slug = url.removeprefix("https://github.com/")
            commit = re.sub(r"[^0-9a-f]", "", row["CommitHash"].lower())
            href = f"{url}/tree/{commit}" if commit else url
            lines.append(
                f'      <li><a href="{html.escape(href)}" rel="external nofollow noopener" target="_blank">'
                f"{html.escape(slug)}</a></li>"
            )
        lines.append("    </ul></div>")
    lines += [
        "  </div>",
        "  <p>Public repositories at the tested commit. Listed as test targets only; inclusion is not an endorsement by their authors.</p>",
        "</details>",
        END,
    ]
    return "\n".join(INDENT + line if line else line for line in lines)


def main() -> int:
    with RESULTS.open(newline="", encoding="utf-8") as handle:
        block = render(list(csv.DictReader(handle)))
    page = PAGE.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(INDENT + START) + r".*?" + re.escape(END), re.S)
    if not pattern.search(page):
        raise SystemExit("migration-wall markers not found in index.html")
    updated = pattern.sub(lambda _: block, page, count=1)
    assert headline(69) == "65+" and headline(70) == "70+"
    if "--check" in sys.argv:
        if updated != page:
            print("Migration wall is out of date: run python3 scripts/render_migration_wall.py")
            return 1
        print("Migration wall is up to date.")
        return 0
    PAGE.write_text(updated, encoding="utf-8")
    print("Migration wall updated.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
