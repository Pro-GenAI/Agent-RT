"""Bake the logo robot (Artie) into python/src/ext/artie_art.py for the CLI banner.

Usage: uv run --with pillow python3 scripts/render_artie_art.py [--check]
The terminal prints two pixels per cell ("▀" with the top pixel as foreground and the
bottom one as background), so the logo is resized to WIDTH pixels and quantized to a
small palette; the runtime then needs no image library.
--check exits 1 when the generated module is out of date instead of rewriting it.
"""

import string
import sys
from pathlib import Path

from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
LOGO = ROOT / "docs/assets/logo-mark.png"
MODULE = ROOT / "python/src/ext/artie_art.py"
WIDTH = 16  # terminal columns; the height follows the logo's aspect ratio
LETTERS = string.ascii_letters  # one palette entry per letter; "." is transparent


def render() -> str:
    logo = Image.open(LOGO).convert("RGBA")
    logo = logo.crop(logo.getbbox())
    height = round(logo.height * WIDTH / logo.width)
    height += height % 2  # whole terminal rows
    # Premultiplied alpha keeps transparent edges from bleeding dark fringes into the colors.
    small = logo.convert("RGBa").resize((WIDTH, height), Image.LANCZOS).convert("RGBA")
    opaque = [small.getpixel((x, y))[3] >= 128 for y in range(height) for x in range(WIDTH)]
    flat = Image.new("RGB", small.size, (255, 255, 255))
    flat.paste(small, mask=small.getchannel("A"))
    # A light sharpen keeps the visor eyes readable at this size.
    flat = flat.filter(ImageFilter.UnsharpMask(radius=1, percent=80, threshold=0))
    quantized = flat.quantize(colors=len(LETTERS), method=Image.Quantize.MEDIANCUT)
    raw = quantized.getpalette()
    indexes = list(quantized.getdata())
    used = sorted({i for i, keep in zip(indexes, opaque) if keep})
    letter = {index: LETTERS[n] for n, index in enumerate(used)}
    rows = [
        "".join(
            letter[indexes[y * WIDTH + x]] if opaque[y * WIDTH + x] else "."
            for x in range(WIDTH)
        )
        for y in range(height)
    ]
    palette = "\n".join(
        f'    "{letter[i]}": "#{raw[3 * i]:02x}{raw[3 * i + 1]:02x}{raw[3 * i + 2]:02x}",'
        for i in used
    )
    pixels = "\n".join(f'    "{row}",' for row in rows)
    return (
        '"""Artie, the logo robot, as pixels for the CLI banner (two pixels per terminal row).\n\n'
        "Generated by scripts/render_artie_art.py from docs/assets/logo-mark.png; do not edit.\n"
        '"""\n\n'
        f"PALETTE = {{\n{palette}\n}}\n\n"
        f'# "." is transparent; every other letter is a PALETTE color.\n'
        f"PIXELS = (\n{pixels}\n)\n"
    )


def main() -> int:
    content = render()
    if "--check" in sys.argv[1:]:
        if MODULE.read_text(encoding="utf-8") != content:
            print(f"{MODULE.relative_to(ROOT)} is out of date; run scripts/render_artie_art.py")
            return 1
        return 0
    MODULE.write_text(content, encoding="utf-8")
    print(f"wrote {MODULE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
